// Beat03SpillwayBridge: beat 3, the spillway bridge (MASTER_PROMPT 14.5.3, s 420-700, MONEY SHOT 2: KS07-KS09), and the
// per-frame driver of the mist volume (14.7 H2: MistVolumeState.Tick every frame and before every capture).
// Replaces the graybox part "beat3" (every graybox piece in the crest band z 420-704: deck, rails, faces, piers, slots,
// gates, gate houses, the fogged cone plume) once this builder renders: [ReplacesGraybox("beat3")].
// Files: SpillwayGeometry.cs (the numbers), SpillwayBuilder.cs (deck with grated slots, piers, gate houses, radial gates,
// rails), SheetBuilder.cs (draw-down water and the 14 near sheets, BwSheet). Materials: the library (ConcreteWet for the
// deck and piers, Concrete for the gate houses, Steel, SteelOchre, Grating, Rail) and two runtime BwSheet materials
// (Shader.Find; Megastructure/BwSheet is in Always Included Shaders after RebuildAll).
// Everything is keyed to s and the ambient clock; nothing is generated after load; no allocations per frame.
using System.Collections.Generic;
using Megastructure.QA;
using Megastructure.Rendering;
using UnityEngine;
using UnityEngine.Rendering;

namespace Megastructure.Beats
{
    [ReplacesGraybox("beat3")]
    public sealed partial class Beat03SpillwayBridge : IBeatBuilder, IWorldUpdater
    {
        public string Name => "Beat03_SpillwayBridge";
        public const string SheetShaderName = "Megastructure/BwSheet";
        static readonly int IdSheetFlow = Shader.PropertyToID("_BwSheetFlow");

        Material m_wet, m_conc, m_dark, m_steel, m_ochre, m_grating, m_rail, m_post, m_water, m_sheet;
        /// <summary>Materials created at runtime by this builder (destroyed by the owner of the build, e.g. EditMode tests).</summary>
        public readonly List<Material> RuntimeMaterials = new List<Material>();
        /// <summary>Root of the beat (tests add colliders below it).</summary>
        public Transform Root { get; private set; }
        /// <summary>Triangles generated by this builder (14.5.3 "about 300 k").</summary>
        public long Triangles { get; private set; }
        /// <summary>Triangles of the 14 near sheets (14.5.3 "18 k").</summary>
        public long SheetTriangles { get; private set; }

        public void Build(WorldContext ctx)
        {
            var root = new GameObject(Name).transform;
            root.SetParent(ctx.Root, false);
            Root = root;
            long t0 = ctx.Triangles;
            MistVolumeNoise.Get();                     // the mist noise tile, behind the load fade
            CreateMaterials(ctx);

            BuildDeck(ctx, root);
            BuildPiers(ctx, root);
            BuildGateHouses(ctx, root);
            BuildGates(ctx, root);
            BuildRails(ctx, root);
            BuildWater(ctx, root);
            long ts = ctx.Triangles;
            BuildSheets(ctx, root);
            SheetTriangles = ctx.Triangles - ts;
            Triangles = ctx.Triangles - t0;

            ctx.Register(this);
            // the mist owner's frame tests (capture set "mistqa", MistQaSet): only when a capture run names the set
            if (QaRigs.Requested(MistQaSet.Set)) QaRigs.Register(MistQaSet.Set, null, MistQaSet.Sequences);
            var ks = BulwarkConst.KeyShots;
            for (int i = 0; i < ks.Length; i++)
                if (ks[i].tag.StartsWith("KS08", System.StringComparison.Ordinal))
                    ctx.PrewarmSets.Add(new PrewarmSet { Name = "Spillway", Eye = new Vector3((float)ks[i].x, (float)ks[i].y, (float)ks[i].z), YawDeg = (float)ks[i].yaw, PitchDeg = (float)ks[i].pitch, Enable = null });
            MistVolumeState.Tick(CliArgs.StartS, BwClock.Ambient);
            ctx.Log($"Beat03_SpillwayBridge: {Triangles} triangles (sheets {SheetTriangles}), mist volume driver registered");
        }

        public void OnFrame(in FrameState f)
        {
            MistVolumeState.Tick(f.s, f.ambientTime, f.cameraPos);
            // flow offset of the water textures (lip-equivalent metres, 8.3 m/s; float precision 1 mm up to 2 h of clock)
            Shader.SetGlobalVector(IdSheetFlow, new Vector4((float)(f.ambientTime * BulwarkConst.LipSpeed), 0f, 0f, 0f));
        }

        // ---------------------------------------------------------------- materials
        void CreateMaterials(WorldContext ctx)
        {
            var lib = ctx.Materials;
            m_wet = lib != null ? lib.ConcreteWet : null;
            m_conc = lib != null ? lib.Concrete : null;
            m_dark = lib != null ? lib.ConcreteDark : null;
            m_steel = lib != null ? lib.Steel : null;
            m_ochre = lib != null ? lib.SteelOchre : null;
            m_grating = lib != null ? lib.Grating : null;
            m_rail = lib != null ? lib.Rail : null;
            if (m_wet == null) m_wet = m_conc;
            if (m_steel == null) m_steel = m_dark;
            if (m_ochre == null) m_ochre = m_steel;
            // the walked grating of the bridge: tops polished by maintenance traffic (_TopWear 0.35 -> 0.6: the 40 mm bar tops,
            // which fill most of every look down, read lighter in the gold light; KS09 mean 94.6 in mistx-02 against the
            // beat-3 band 95-150); the paint colour stays the library's SteelPaint
            if (m_grating != null && m_grating.HasProperty("_TopWear"))
            {
                m_grating = new Material(m_grating) { name = "b03_grating (runtime)" };
                m_grating.SetFloat("_TopWear", 0.6f);
                RuntimeMaterials.Add(m_grating);
            }
            // round 0.12 m rail posts through BwLine like the crest's (CrestBuilder m_post12): the square steel posts of the
            // rounds before showed their sunlit faces as 1-px gold slivers at 50-150 m (mistx-01 back640: 7 NaN-like pixels)
            if (m_rail != null)
            {
                m_post = new Material(m_rail) { name = "b03_post12 (runtime)" };
                if (m_post.HasProperty("_LineWidth")) m_post.SetFloat("_LineWidth", (float)BulwarkConst.LeeRailPostSize);
                RuntimeMaterials.Add(m_post);
            }

            var sheet = Shader.Find(SheetShaderName);
            if (sheet == null)
            {
                Debug.LogError("[BW-FAIL] Beat03: shader " + SheetShaderName + " not found (run RebuildAll so it is in Always Included Shaders)");
                m_water = m_wet; m_sheet = m_wet;
                return;
            }
            m_water = new Material(sheet) { name = "BwSheet_channel (runtime)", enableInstancing = false };
            m_water.SetFloat("_Mode", 0f);
            m_water.SetFloat("_AlphaToMask", 0f);
            m_water.SetFloat("_LipTau", (float)SpillwayGeometry.LipTravelTime);
            m_sheet = new Material(sheet) { name = "BwSheet_fall (runtime)", enableInstancing = false };
            m_sheet.SetFloat("_Mode", 1f);
            m_sheet.SetFloat("_AlphaToMask", 1f);
            m_sheet.SetFloat("_LipTau", (float)SpillwayGeometry.LipTravelTime);
            RuntimeMaterials.Add(m_water);
            RuntimeMaterials.Add(m_sheet);
        }

        // ---------------------------------------------------------------- mesh helpers
        static void BoxMinMax(MeshBuilder mb, double x0, double y0, double z0, double x1, double y1, double z1)
        {
            var c = new Vector3((float)(0.5 * (x0 + x1)), (float)(0.5 * (y0 + y1)), (float)(0.5 * (z0 + z1)));
            var size = new Vector3((float)System.Math.Abs(x1 - x0), (float)System.Math.Abs(y1 - y0), (float)System.Math.Abs(z1 - z0));
            mb.Box(c, size);
        }

        static void CBox(MeshBuilder mb, double x0, double y0, double z0, double x1, double y1, double z1, float bevel = 0.02f)
        {
            var c = new Vector3((float)(0.5 * (x0 + x1)), (float)(0.5 * (y0 + y1)), (float)(0.5 * (z0 + z1)));
            var size = new Vector3((float)System.Math.Abs(x1 - x0), (float)System.Math.Abs(y1 - y0), (float)System.Math.Abs(z1 - z0));
            MeshKit.ChamferBox(mb, c, size, bevel);
        }

        /// <summary>Round tube from a to b (BwLine _LINE_TUBE contract, D-07): smooth outward normals, a ring at least every
        /// 4 m, open ends.</summary>
        static void Tube(MeshBuilder mb, Vector3 a, Vector3 b, float radius, int sides = 8)
        {
            Vector3 d = b - a;
            float len = d.magnitude;
            if (len < 1e-4f || radius <= 0f) return;
            Vector3 dir = d / len;
            Vector3 h = Mathf.Abs(dir.y) < 0.9f ? Vector3.up : Vector3.right;
            Vector3 u = Vector3.Cross(h, dir).normalized, v = Vector3.Cross(dir, u);
            int rings = Mathf.Max(2, Mathf.CeilToInt(len / 4f) + 1);
            int first = mb.VertexCount;
            for (int i = 0; i < rings; i++)
            {
                Vector3 c = a + d * (i / (float)(rings - 1));
                for (int j = 0; j < sides; j++)
                {
                    float ph = 2f * Mathf.PI * j / sides;
                    Vector3 n = u * Mathf.Cos(ph) + v * Mathf.Sin(ph);
                    mb.Vertex(c + n * radius, n);
                }
            }
            for (int i = 0; i + 1 < rings; i++)
                for (int j = 0; j < sides; j++)
                {
                    int a0 = first + i * sides + j, a1 = first + i * sides + (j + 1) % sides;
                    int b0 = a0 + sides, b1 = a1 + sides;
                    mb.Quad(a0, a1, b1, b0);   // outward (cross(a1 - a0, b1 - a0) points away from the axis)
                }
        }

        static float LineRadius(Material m, float fallback)
        {
            if (m != null && m.HasProperty("_LineWidth")) { float w = m.GetFloat("_LineWidth"); if (w > 1e-4f) return 0.5f * w; }
            return fallback;
        }

        MeshRenderer Flush(WorldContext ctx, Transform root, ref MeshBuilder mb, string name, Material mat, bool shadows = true)
        {
            MeshRenderer mr = null;
            if (mb.VertexCount > 0 && mat != null)
            {
                mr = ctx.AddMesh(root, name, mb.ToMesh(name), mat, shadows, true);
                if (!shadows) mr.shadowCastingMode = ShadowCastingMode.Off;
            }
            mb = new MeshBuilder();
            return mr;
        }
    }
}
