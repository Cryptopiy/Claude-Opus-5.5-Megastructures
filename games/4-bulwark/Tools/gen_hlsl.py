#!/usr/bin/env python3
"""Bootstrap generator of the two shader includes (imported from Thread's Tools/gen_hlsl.py):

  Assets/_Game/Shaders/Include/BulwarkPalette.hlsl     PAL_<Token> float3 macros from BulwarkPalette.Table
                                                        (text identical to BulwarkPalette.ToHlsl(), checked by PaletteTests)
  Assets/_Game/Shaders/Generated/BulwarkConstGen.hlsl  TC_<Name> macros for every `public const double|float|int NAME = literal;`
                                                        of BulwarkConst (identical to ShaderGen.ConstantsHlsl(), ProjectTests)

The authoritative generator is the editor script (Megastructure.EditorTools.ShaderGen, run by RebuildAll); this script produces
byte-identical output (LF, UTF-8 without BOM, f6 = "{v:.6f}" with trailing zeros trimmed and at least one decimal) so shaders
compile before the first RebuildAll. Both read the same C# sources.

Usage: python -I Tools/gen_hlsl.py [--check]    (--check: compare with the files on disk, write nothing, exit 1 on a difference)
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CORE = os.path.join(ROOT, "Assets", "_Game", "Scripts", "Runtime", "Core")
PALETTE_OUT = os.path.join(ROOT, "Assets", "_Game", "Shaders", "Include", "BulwarkPalette.hlsl")
CONST_OUT = os.path.join(ROOT, "Assets", "_Game", "Shaders", "Generated", "BulwarkConstGen.hlsl")


def srgb_to_linear(c):
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def f6(v):
    s = f"{v:.6f}".rstrip("0")
    if s.endswith("."):
        s += "0"
    return s


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def palette():
    with open(os.path.join(CORE, "BulwarkPalette.cs"), encoding="utf-8-sig") as f:
        text = strip_comments(f.read())
    pairs = re.findall(r"\(Pal\.(\w+),\s*\"#([0-9A-Fa-f]{6})\"\)", text)
    lines = ["// GENERATED from BulwarkPalette.ToHlsl() (Megastructure.BulwarkPalette.Table, MASTER_PROMPT 14.2.1) - do not edit.",
             "// Linear RGB of each sRGB token (exact sRGB EOTF). PaletteTests checks this file equals ToHlsl().",
             "#ifndef BULWARK_PALETTE_INCLUDED", "#define BULWARK_PALETTE_INCLUDED"]
    for name, hx in pairs:
        r, g, b = (int(hx[i:i + 2], 16) / 255.0 for i in (0, 2, 4))
        lin = [srgb_to_linear(c) for c in (r, g, b)]
        lines.append(f"#define PAL_{name} float3({f6(lin[0])}, {f6(lin[1])}, {f6(lin[2])})")
    lines.append("#endif")
    return "\n".join(lines) + "\n"


def constants():
    with open(os.path.join(CORE, "BulwarkConst.cs"), encoding="utf-8-sig") as f:
        text = strip_comments(f.read())
    lines = ["// GENERATED by RebuildAll (ShaderGen) from BulwarkConst - do not edit.",
             "#ifndef BULWARK_CONSTANTS_INCLUDED", "#define BULWARK_CONSTANTS_INCLUDED"]
    for m in re.finditer(r"public const (double|float|int) ([^;]+);", text):
        decls = m.group(2)
        for part in re.split(r",\s*(?=\w+\s*=)", decls):
            name, val = [x.strip() for x in part.split("=", 1)]
            val = val.rstrip("fFdD")
            try:
                v = float(val)
            except ValueError:
                raise SystemExit(f"gen_hlsl: BulwarkConst.{name} is not a plain literal ({val}); keep consts literal")
            lines.append(f"#define TC_{name} {f6(v)}")
    lines.append("#endif")
    return "\n".join(lines) + "\n"


def write_or_check(path, text, check):
    data = text.encode("utf-8")
    old = open(path, "rb").read() if os.path.exists(path) else None
    if check:
        same = old == data
        print(("same     " if same else "DIFFERS  ") + os.path.relpath(path, ROOT))
        return same
    if old != data:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "wb") as f:
            f.write(data)
        print("written  " + os.path.relpath(path, ROOT))
    else:
        print("unchanged " + os.path.relpath(path, ROOT))
    return True


def main():
    check = "--check" in sys.argv[1:]
    ok = write_or_check(PALETTE_OUT, palette(), check)
    ok = write_or_check(CONST_OUT, constants(), check) and ok
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
