// ShaderGen (imported from Thread): the authoritative generator of Assets/_Game/Shaders/Generated/NocPalette.hlsl (PAL_* macros,
// MASTER_PROMPT 14.7.8) and one NC_ header per constants class (TEXTURE_PLAN 8.3 TP-0; ConstantClasses: NocturneConstants ->
// NocConstantsGen.hlsl, NocFacadeConstants (FA) -> NocFacadeConstantsGen.hlsl, NocSurfaceConstants (SU) ->
// NocSurfaceConstantsGen.hlsl, NocTexConstants (TP) -> NocTexConstantsGen.hlsl; NC_* macros for every public const
// double/float/int; a class that does not exist yet gets no header; a NC_ name exported by two classes is an error and nothing
// is written). The output is BYTE-IDENTICAL to Tools/gen_hlsl.py (the bootstrap generator):
//   - same header lines, LF line endings, UTF-8 without BOM, trailing newline;
//   - values formatted by the "f6" rule: Python f"{v:.6f}" (correctly rounded, ties to even, on the exact
//     binary value of the double), trailing zeros trimmed, at least one decimal;
//   - palette values in double: srgb_to_linear(int(hex)/255.0) with the piecewise sRGB EOTF;
//   - constants in declaration order (metadata order of the const fields); a float const is first turned
//     into its shortest round-trip decimal string, because Python parses the literal text as a double.
// ProjectTests verifies the equality against a run of the Python script and against the files on disk.
using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Numerics;
using System.Reflection;
using System.Text;
using UnityEditor;

namespace Megastructure.EditorTools
{
    public static class ShaderGen
    {
        static readonly UTF8Encoding s_Utf8NoBom = new UTF8Encoding(false);
        static readonly BigInteger s_Million = new BigInteger(1000000);

        /// <summary>Exact port of gen_hlsl.py f6(): "{v:.6f}" with trailing zeros trimmed, at least one decimal.</summary>
        public static string F6(double v)
        {
            if (double.IsNaN(v) || double.IsInfinity(v)) throw new ArgumentException("F6: value is not finite: " + v.ToString(CultureInfo.InvariantCulture));
            long bits = BitConverter.DoubleToInt64Bits(v);
            bool negative = bits < 0;                       // Python keeps the sign of -0.0 and of values that round to 0
            int exponent = (int)((bits >> 52) & 0x7FF);
            long mantissa = bits & 0xFFFFFFFFFFFFFL;
            if (exponent == 0) exponent = 1;                // subnormal: m * 2^(1 - 1075)
            else mantissa |= 1L << 52;
            int e2 = exponent - 1075;                       // |v| = mantissa * 2^e2 exactly

            BigInteger num = new BigInteger(mantissa) * s_Million;   // |v| * 10^6 = num * 2^e2
            BigInteger q;
            if (e2 >= 0) q = num << e2;
            else
            {
                BigInteger den = BigInteger.One << (-e2);
                q = BigInteger.DivRem(num, den, out BigInteger rem);
                int c = (rem << 1).CompareTo(den);
                if (c > 0 || (c == 0 && !q.IsEven)) q += BigInteger.One;   // round half to even (Python's dtoa)
            }
            BigInteger ip = BigInteger.DivRem(q, s_Million, out BigInteger fp);
            string s = (negative ? "-" : "") + ip.ToString(CultureInfo.InvariantCulture) + "." +
                       fp.ToString(CultureInfo.InvariantCulture).PadLeft(6, '0');
            s = s.TrimEnd('0');
            if (s.EndsWith(".", StringComparison.Ordinal)) s += "0";
            return s;
        }

        /// <summary>Content of Generated/NocPalette.hlsl.</summary>
        public static string PaletteHlsl()
        {
            var sb = new StringBuilder(4096);
            sb.Append("// GENERATED by RebuildAll (ShaderGen) from NocturnePalette.Table - do not edit.\n");
            sb.Append("#ifndef NOC_PALETTE_INCLUDED\n");
            sb.Append("#define NOC_PALETTE_INCLUDED\n");
            var table = NocturnePalette.Table;
            for (int i = 0; i < table.Length; i++)
            {
                string h = table[i].hex.TrimStart('#');
                double r = NocturnePalette.SrgbToLinear(Convert.ToInt32(h.Substring(0, 2), 16) / 255.0);
                double g = NocturnePalette.SrgbToLinear(Convert.ToInt32(h.Substring(2, 2), 16) / 255.0);
                double b = NocturnePalette.SrgbToLinear(Convert.ToInt32(h.Substring(4, 2), 16) / 255.0);
                sb.Append("#define PAL_").Append(table[i].id.ToString()).Append(" float3(")
                  .Append(F6(r)).Append(", ").Append(F6(g)).Append(", ").Append(F6(b)).Append(")\n");
            }
            sb.Append("#endif\n");
            return sb.ToString();
        }

        /// <summary>One generated NC_ header per constants class (same table as CLASSES in Tools/gen_hlsl.py).</summary>
        public struct ConstantClass
        {
            public string ClassName, Header, Guard;
            public ConstantClass(string c, string h, string g) { ClassName = c; Header = h; Guard = g; }
            /// <summary>Asset path of the generated header.</summary>
            public string AssetPath => NocPaths.GeneratedDir + "/" + Header;
            /// <summary>The runtime type (null while the class does not exist).</summary>
            public Type Type => typeof(NocturneConstants).Assembly.GetType("Megastructure." + ClassName, false);
        }

        public static readonly ConstantClass[] ConstantClasses =
        {
            new ConstantClass("NocturneConstants", "NocConstantsGen.hlsl", "NOC_CONSTANTS_INCLUDED"),
            new ConstantClass("NocFacadeConstants", "NocFacadeConstantsGen.hlsl", "NOC_FACADE_CONSTANTS_INCLUDED"),
            new ConstantClass("NocSurfaceConstants", "NocSurfaceConstantsGen.hlsl", "NOC_SURFACE_CONSTANTS_INCLUDED"),
            new ConstantClass("NocTexConstants", "NocTexConstantsGen.hlsl", "NOC_TEX_CONSTANTS_INCLUDED"),
        };

        /// <summary>The const fields of NocturneConstants exported as NC_* macros, in declaration order.</summary>
        public static List<FieldInfo> ExportedConstants() => ExportedConstants(typeof(NocturneConstants));

        /// <summary>The const fields of a class exported as NC_* macros, in declaration order.</summary>
        public static List<FieldInfo> ExportedConstants(Type type)
        {
            var fields = new List<FieldInfo>();
            if (type == null) return fields;
            foreach (var f in type.GetFields(BindingFlags.Public | BindingFlags.Static | BindingFlags.DeclaredOnly))
            {
                if (!f.IsLiteral || f.IsInitOnly) continue;
                var ft = f.FieldType;
                if (ft == typeof(double) || ft == typeof(float) || ft == typeof(int)) fields.Add(f);
            }
            // Metadata order is declaration order for fields emitted by Roslyn; sort explicitly so the result
            // does not depend on the runtime's reflection ordering.
            fields.Sort((a, b) => a.MetadataToken.CompareTo(b.MetadataToken));
            return fields;
        }

        /// <summary>The value Python's float(literal) would produce for this const field.</summary>
        public static double ConstantAsPythonDouble(FieldInfo f)
        {
            object raw = f.GetRawConstantValue();
            if (raw is double d) return d;
            if (raw is int i) return i;
            if (raw is float fl)
            {
                // Shortest round-trip text of the float = the source literal for every literal with <= 9 significant digits.
                string txt = fl.ToString("R", CultureInfo.InvariantCulture);
                return double.Parse(txt, NumberStyles.Float, CultureInfo.InvariantCulture);
            }
            throw new InvalidOperationException("ShaderGen: unsupported const type " + f.FieldType.Name + " for " + f.Name);
        }

        /// <summary>Content of Generated/NocConstantsGen.hlsl.</summary>
        public static string ConstantsHlsl() => ConstantsHlsl(ConstantClasses[0]);

        /// <summary>Content of the generated header of one constants class (null while the class does not exist).</summary>
        public static string ConstantsHlsl(ConstantClass c)
        {
            Type t = c.Type;
            if (t == null) return null;
            var sb = new StringBuilder(16384);
            sb.Append("// GENERATED by RebuildAll (ShaderGen) from ").Append(c.ClassName).Append(" - do not edit.\n");
            sb.Append("#ifndef ").Append(c.Guard).Append('\n');
            sb.Append("#define ").Append(c.Guard).Append('\n');
            var fields = ExportedConstants(t);
            for (int i = 0; i < fields.Count; i++)
                sb.Append("#define NC_").Append(fields[i].Name).Append(' ').Append(F6(ConstantAsPythonDouble(fields[i]))).Append('\n');
            sb.Append("#endif\n");
            return sb.ToString();
        }

        /// <summary>NC_ names exported by more than one class ("NC_NAME: A, B"); empty when the headers may be written.</summary>
        public static List<string> DuplicateConstantNames()
        {
            var owner = new Dictionary<string, string>();
            var dups = new List<string>();
            foreach (var c in ConstantClasses)
                foreach (var f in ExportedConstants(c.Type))
                {
                    if (owner.TryGetValue(f.Name, out string first)) dups.Add("NC_" + f.Name + ": " + first + ", " + c.ClassName);
                    else owner[f.Name] = c.ClassName;
                }
            return dups;
        }

        public static byte[] Encode(string text) => s_Utf8NoBom.GetBytes(text);

        /// <summary>Writes the palette and every constants header (only when the bytes differ, so an unchanged run triggers no
        /// reimport). A duplicate NC_ name throws and writes nothing (RebuildAll reports it as a failed step).</summary>
        public static int WriteAll()
        {
            var dups = DuplicateConstantNames();
            if (dups.Count > 0) throw new InvalidOperationException("ShaderGen: NC_ names exported by two classes: " + string.Join("; ", dups));
            EditorUtil.EnsureFolder(NocPaths.GeneratedDir);
            int changed = 0, total = 0, headers = 0;
            changed += WriteIfChanged(NocPaths.PaletteHlsl, PaletteHlsl());
            foreach (var c in ConstantClasses)
            {
                string text = ConstantsHlsl(c);
                if (text == null) continue;
                changed += WriteIfChanged(c.AssetPath, text);
                total += ExportedConstants(c.Type).Count;
                headers++;
            }
            NocLog.Info($"ShaderGen: {NocturnePalette.Table.Length} PAL_ tokens, {total} NC_ constants in {headers} header(s), {changed} file(s) changed");
            return changed;
        }

        static int WriteIfChanged(string assetPath, string text)
        {
            string abs = NocPaths.Abs(assetPath);
            byte[] bytes = Encode(text);
            if (File.Exists(abs))
            {
                byte[] old = File.ReadAllBytes(abs);
                if (BytesEqual(old, bytes)) return 0;
            }
            File.WriteAllBytes(abs, bytes);
            AssetDatabase.ImportAsset(assetPath, ImportAssetOptions.ForceSynchronousImport);
            NocLog.Info("ShaderGen: wrote " + assetPath);
            return 1;
        }

        public static bool BytesEqual(byte[] a, byte[] b)
        {
            if (a == null || b == null || a.Length != b.Length) return false;
            for (int i = 0; i < a.Length; i++) if (a[i] != b[i]) return false;
            return true;
        }
    }
}
