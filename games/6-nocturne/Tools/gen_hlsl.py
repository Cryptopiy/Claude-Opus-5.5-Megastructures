#!/usr/bin/env python3
"""Bootstrap generator for Assets/_Game/Shaders/Generated/NocPalette.hlsl and one NC_ header per constants class.

The authoritative generator is the editor script (Megastructure.EditorTools.ShaderGen, run by
RebuildAll); this script produces byte-identical output so shaders compile before the first
RebuildAll. Both read the same C# sources (NocturnePalette.Table, the const fields of each class of CLASSES).
Only `public const double|float|int NAME = <literal>;` fields are exported (computed values are static readonly);
an int literal may be decimal or hex (0x..). Comments are ignored. A NC_ name exported by two classes is an error
(TEXTURE_PLAN 8.3 TP-0): the run aborts and writes nothing.
Usage: python -I Tools/gen_hlsl.py [out_dir]   (default Assets/_Game/Shaders/Generated; ProjectTests passes a temp dir)
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CORE = os.path.join(ROOT, "Assets", "_Game", "Scripts", "Runtime", "Core")
OUT = os.path.join(ROOT, "Assets", "_Game", "Shaders", "Generated")

# (C# class = source file name, generated header, include guard). Same table as ShaderGen.ConstantClasses (ProjectTests).
CLASSES = [
    ("NocturneConstants", "NocConstantsGen.hlsl", "NOC_CONSTANTS_INCLUDED"),
    ("NocFacadeConstants", "NocFacadeConstantsGen.hlsl", "NOC_FACADE_CONSTANTS_INCLUDED"),
    ("NocSurfaceConstants", "NocSurfaceConstantsGen.hlsl", "NOC_SURFACE_CONSTANTS_INCLUDED"),
    ("NocTexConstants", "NocTexConstantsGen.hlsl", "NOC_TEX_CONSTANTS_INCLUDED"),
]


def srgb_to_linear(c):
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def f6(v):
    # formatting identical to the C# generator: "0.######" invariant, trailing zeros trimmed, at least one decimal
    s = f"{v:.6f}".rstrip("0")
    if s.endswith("."):
        s += "0"
    return s


def strip_comments(text):
    # block comments, then line comments (no const of an exported type holds a string, so "//" inside strings is harmless)
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def literal_value(cls, name, val):
    v = val.strip().replace("_", "")
    if re.fullmatch(r"[+-]?0[xX][0-9A-Fa-f]+", v):
        return float(int(v, 16))
    v = re.sub(r"[fFdDmM]$", "", v)
    try:
        return float(v)
    except ValueError:
        raise SystemExit(f"gen_hlsl: {cls}.{name} = '{val.strip()}' is not a literal (export literals only; computed values are static readonly)")


def palette():
    with open(os.path.join(CORE, "NocturnePalette.cs"), encoding="utf-8") as f:
        text = f.read()
    pairs = re.findall(r"\(NocPal\.(\w+),\s*\"#([0-9A-Fa-f]{6})\"\)", text)
    lines = ["// GENERATED by RebuildAll (ShaderGen) from NocturnePalette.Table - do not edit.",
             "#ifndef NOC_PALETTE_INCLUDED", "#define NOC_PALETTE_INCLUDED"]
    for name, hx in pairs:
        r, g, b = (int(hx[i:i + 2], 16) / 255.0 for i in (0, 2, 4))
        lin = [srgb_to_linear(c) for c in (r, g, b)]
        lines.append(f"#define PAL_{name} float3({f6(lin[0])}, {f6(lin[1])}, {f6(lin[2])})")
    lines.append("#endif")
    return "\n".join(lines) + "\n"


def class_constants(cls):
    """[(name, value)] in declaration order; [] when the class file does not exist yet."""
    path = os.path.join(CORE, cls + ".cs")
    if not os.path.isfile(path):
        return None
    with open(path, encoding="utf-8") as f:
        text = strip_comments(f.read())
    out = []
    for m in re.finditer(r"public const (double|float|int) ([^;]+);", text):
        for part in re.split(r",\s*(?=\w+\s*=)", m.group(2)):
            name, val = [x.strip() for x in part.split("=", 1)]
            out.append((name, literal_value(cls, name, val)))
    return out


def constants_header(cls, guard, consts):
    lines = [f"// GENERATED by RebuildAll (ShaderGen) from {cls} - do not edit.", f"#ifndef {guard}", f"#define {guard}"]
    for name, v in consts:
        lines.append(f"#define NC_{name} {f6(v)}")
    lines.append("#endif")
    return "\n".join(lines) + "\n"


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else OUT   # optional output folder (ProjectTests compares against ShaderGen)
    files = {"NocPalette.hlsl": palette()}
    seen = {}
    for cls, header, guard in CLASSES:
        consts = class_constants(cls)
        if consts is None:
            continue                                  # a class not created yet gets no header (ShaderGen does the same)
        for name, _ in consts:
            if name in seen:
                raise SystemExit(f"gen_hlsl: NC_{name} is exported by both {seen[name]} and {cls}")
            seen[name] = cls
        files[header] = constants_header(cls, guard, consts)
    os.makedirs(out, exist_ok=True)
    for name, text in files.items():
        with open(os.path.join(out, name), "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    print("written", out, ", ".join(files))


if __name__ == "__main__":
    main()
